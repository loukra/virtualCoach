"""Deterministic workout handling: duration, TSS, Zwift export and the text the app shows.

The LLM only decides the structure; every number derived from it is computed here.
"""
import xml.etree.ElementTree as ET

from logic.schemas import Workout, WorkoutStep


def step_segments(step: WorkoutStep) -> list[tuple[int, float, float]]:
    """Splits a step into (seconds, start power, end power) segments."""
    if step.kind == "intervals":
        segments = []
        for _ in range(step.repeat or 0):
            segments.append((step.on_s or 0, step.on_power or 0, step.on_power or 0))
            segments.append((step.off_s or 0, step.off_power or 0, step.off_power or 0))
        return segments
    if step.kind == "steady":
        return [(step.duration_s or 0, step.power or 0, step.power or 0)]
    return [(step.duration_s or 0, step.power_low or 0, step.power_high or 0)]


def total_duration_s(workout: Workout) -> int:
    return sum(sec for step in workout.steps for sec, _, _ in step_segments(step))


def max_power(workout: Workout) -> float:
    return max(
        (max(lo, hi) for step in workout.steps for _, lo, hi in step_segments(step)),
        default=0.0,
    )


def estimate_tss(workout: Workout) -> int:
    """TSS = sum(seconds * IF^2) / 3600 * 100, with IF = power / FTP.

    For a linear ramp the mean of IF^2 is (a^2 + ab + b^2) / 3.
    """
    total = 0.0
    for step in workout.steps:
        for sec, lo, hi in step_segments(step):
            total += sec * (lo * lo + lo * hi + hi * hi) / 3
    return round(total / 3600 * 100)


def to_zwo(workout: Workout) -> str:
    """Zwift .zwo XML for the workout, built from data rather than generated by the LLM."""
    root = ET.Element("workout_file")
    ET.SubElement(root, "author").text = "Virtual Coach"
    ET.SubElement(root, "name").text = workout.name
    ET.SubElement(root, "description").text = workout.rationale
    ET.SubElement(root, "sportType").text = "bike"
    body = ET.SubElement(root, "workout")

    def fmt(value: float | None) -> str:
        return f"{value or 0:.2f}"

    tags = {"warmup": "Warmup", "cooldown": "Cooldown", "ramp": "Ramp"}
    for step in workout.steps:
        if step.kind == "intervals":
            ET.SubElement(
                body,
                "IntervalsT",
                Repeat=str(step.repeat),
                OnDuration=str(step.on_s),
                OffDuration=str(step.off_s),
                OnPower=fmt(step.on_power),
                OffPower=fmt(step.off_power),
            )
        elif step.kind == "steady":
            ET.SubElement(body, "SteadyState", Duration=str(step.duration_s), Power=fmt(step.power))
        else:
            ET.SubElement(
                body,
                tags[step.kind],
                Duration=str(step.duration_s),
                PowerLow=fmt(step.power_low),
                PowerHigh=fmt(step.power_high),
            )

    ET.indent(root)
    return ET.tostring(root, encoding="unicode")


def _watts(fraction: float | None, ftp: int) -> int:
    return round((fraction or 0) * ftp)


def _minutes(seconds: int | None) -> str:
    seconds = seconds or 0
    return f"{seconds // 60} min" if seconds % 60 == 0 else f"{seconds / 60:.1f} min"


def to_markdown(workout: Workout, ftp: int) -> str:
    """The text the app renders. Watts come from FTP here, so they always match the plan."""
    titles = {
        "warmup": "Warmup",
        "steady": "Steady",
        "intervals": "Intervals",
        "ramp": "Ramp",
        "cooldown": "Cooldown",
    }
    lines = [f"# {workout.name}", "", workout.rationale, ""]
    for step in workout.steps:
        if step.kind == "intervals":
            # Every repeat includes its recovery, the last one too (as in the .zwo file).
            block_s = (step.repeat or 0) * ((step.on_s or 0) + (step.off_s or 0))
            target = (
                f"**{step.repeat} ×** {_minutes(step.on_s)} @ **{_watts(step.on_power, ftp)} W**,"
                f" each followed by {_minutes(step.off_s)} easy @ {_watts(step.off_power, ftp)} W"
                f" ({_minutes(block_s)} in total)"
            )
        elif step.kind == "steady":
            target = f"**{_minutes(step.duration_s)}** @ **{_watts(step.power, ftp)} W**"
        else:
            target = (
                f"**{_minutes(step.duration_s)}** from {_watts(step.power_low, ftp)}"
                f" to **{_watts(step.power_high, ftp)} W**"
            )
        cap = f" · HR cap **{step.hr_cap_bpm} bpm**" if step.hr_cap_bpm else ""
        lines += [f"## {titles[step.kind]}", f"- {target}{cap}", f"- {step.instruction}", ""]

    lines += [
        "## Summary",
        f"- Duration: **{_minutes(total_duration_s(workout))}**",
        f"- Estimated TSS: **{estimate_tss(workout)}**",
        f"- {workout.hr_guidance}",
    ]
    return "\n".join(lines)
